/*
 * File: art/logo.h
 * Purpose: The mark of Oxys-OS as a bitmap, two bits to a pixel, generated
 *          from art/logo.png and included by whatever draws it.
 * Key definitions: LOGO_WIDTH, LOGO_HEIGHT, LOGO_NOTHING, LOGO_DISC,
 *          LOGO_INK, LogoBits, LogoAt.
 * References:
 *   - art/README.md: how this is generated, and why it is generated rather
 *     than drawn.
 *   - docs/design/SESSION.md, Section 3.2: where it is drawn and why the
 *     boot screen and the desktop must draw the same thing.
 *
 * Three states and not two, which is why it is two bits: a pixel is nothing,
 * and the ground behind shows through; or it is the disc; or it is the ink
 * the figure and the outline are drawn in. A mask of one bit would make the
 * figure and the ground one thing, and the mark is a figure *upon* a disc.
 *
 * The colours are not here. A caller supplies them, as every drawing in this
 * system does, because a pixel value means nothing without an encoding.
 */

