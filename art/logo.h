/* The state of one pixel: LOGO_NOTHING, LOGO_DISC or LOGO_INK. */
static inline unsigned LogoAt(int x, int y)
{
    unsigned index;
    unsigned shift;

    if ((x < 0) || (y < 0) || (x >= LOGO_WIDTH) || (y >= LOGO_HEIGHT))
    {
        return LOGO_NOTHING;
    }

    index = (unsigned)((y * LOGO_WIDTH) + x) / 4U;
    shift = 6U - (2U * ((unsigned)x % 4U));

    return ((unsigned)LogoBits[index] >> shift) & 3U;
}

